#!/usr/bin/env node
// Generates views/partials/icon.liquid from tokens/icon-registry.json and the Tabler icon set
// (@tabler/icons, MIT). Run: npm run build:icons
//   - each registry entry: name (logical name callers use), tabler (Tabler icon name),
//     tablerStyle ('outline' default | 'filled'), extraPaths (extra <path d>), rotate (degrees), aliases, inAll
//   - outline icons get an inline fill:none (the global .pos-icon { fill: currentColor } would
//     fill them otherwise) and the DS stroke width below
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const registryFile = path.join(root, 'modules/common-styling/public/assets/tokens/icon-registry.json');
const outFile = path.join(root, 'modules/common-styling/public/views/partials/icon.liquid');
const tablerDir = path.join(root, 'node_modules/@tabler/icons/icons');
const STROKE_WIDTH = 1.5; // matches the Figma icon set's line weight
// Tabler draws inside a 2px safe zone of its 24px grid; cropping it makes the glyphs as large as
// the Streamline set the Figma file uses (≈22px of 24) at the same line weight
const VIEWBOX = '2 2 20 20';
const DATA_ICON = { 'navigation-menu-vertical': 'more-vertical' }; // data-icon kept for existing CSS / callers

const registry = JSON.parse(fs.readFileSync(registryFile, 'utf8'));
const entries = new Map(registry.categories.flatMap((c) => c.icons).map((i) => [i.name, i]));
const order = [...(registry.order || []), ...[...entries.keys()].filter((n) => !(registry.order || []).includes(n))];

function glyph(entry) {
  const style = entry.tablerStyle === 'filled' ? 'filled' : 'outline';
  const file = path.join(tablerDir, style, `${entry.tabler}.svg`);
  if (!fs.existsSync(file)) throw new Error(`Tabler icon not found: ${style}/${entry.tabler} (registry entry "${entry.name}")`);
  const svg = fs.readFileSync(file, 'utf8');
  const inner = svg.slice(svg.indexOf('>') + 1, svg.lastIndexOf('</svg>'))
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/g, '')
    .replace(/\s*\n\s*/g, '').trim();
  const extra = (entry.extraPaths || []).map((d) => `<path d="${d}" />`).join('');
  const body = entry.rotate ? `<g transform="rotate(${entry.rotate} 12 12)">${inner}${extra}</g>` : `${inner}${extra}`;
  const paint = style === 'filled'
    ? 'style="fill:currentColor;stroke:none;overflow:visible"'
    : `style="fill:none;overflow:visible" stroke="currentColor" stroke-width="${STROKE_WIDTH}" stroke-linecap="round" stroke-linejoin="round"`;
  return `<svg data-icon="${DATA_ICON[entry.name] || entry.name}" {{ attrs | html_safe }} ${paint}>${body}</svg>`;
}

const cases = order.map((name) => {
  const e = entries.get(name);
  const names = [name, ...(e.aliases || []), ...(e.inAll ? ['all'] : [])].map((n) => `'${n}'`).join(', ');
  return `  {% when ${names} %}\n  ${glyph(e)}\n`;
}).join('\n');

const out = `{% comment %}

  Generated by scripts/build-icons.mjs from tokens/icon-registry.json — do not edit by hand:
  add or change the registry entry, then run \`npm run build:icons\`.

  Icons: Tabler Icons (https://tabler.io/icons), MIT License, © Paweł Kuna.

  Params:
    - icon name (string)
    - class (string, optional)
    - aria_hidden (bool, optional) — true for a decorative icon next to text (hidden from
      screen readers instead of being announced as an unnamed image)

{% endcomment %}


{% liquid
  assign class = class | default: ''
%}

{% capture attrs %}
  viewBox="${VIEWBOX}"
  fill="none"
  class="pos-icon {{ class }}"
  focusable="false"
  overflow="visible"
  {% if aria_hidden %}aria-hidden="true"{% else %}role="img"{% endif %}
  xmlns="http://www.w3.org/2000/svg"
{% endcapture %}


{% case icon %}

${cases}
  {% else %}
  <script>
    window.addEventListener('load', function() { throw new Error('Missing icon: {{ icon | raw_escape_string }}'); })
  </script>

{% endcase %}
`;
fs.writeFileSync(outFile, out);
console.log(`icon.liquid: ${order.length} icons from Tabler (${STROKE_WIDTH}px stroke, viewBox ${VIEWBOX})`);
