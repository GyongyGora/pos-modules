#!/usr/bin/env node
// Builds style/pos-themes.css from tokens/themes.json (npm run build:themes).
//
// For every theme the 10-step brand-primary and brand-supplementary scales are computed from its two
// base colors with the palette math of assets/style-guide/palettes.js (the part between
// "---------- config" and "---------- state" — the same code the Palettes page runs), using the default
// contrast targets. A theme only overrides those 20 primitives under :root.pos-brand-<key>; the
// semantic and component tokens already point at them. The scales are also written back into
// themes.json (computed: …) for the Themes docs page. Default writes no CSS block (it is the base).
//
// Optional graphicStep (600 default | 700 | 800): the step of the interactive graphics — buttons, icons,
// toggles — in light mode. Every step from 600 up passes the graphics contrast (3:1), from 700 up the
// text contrast too, so a deeper brand color can fill the buttons. Hover / active stay two steps
// darker (hence 800 at most); dark mode gets the mirrored step (700 -> 400, which is the current
// dark value, 800 -> 300). Written as role-token overrides in the theme's block; disabled is unchanged.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const assets = path.join(root, 'modules/common-styling/public/assets');
const themesPath = path.join(assets, 'tokens/themes.json');
const cssPath = path.join(assets, 'style/pos-themes.css');

const palettes = fs.readFileSync(path.join(assets, 'style-guide/palettes.js'), 'utf8');
const math = palettes.slice(palettes.indexOf('/* ---------- config'), palettes.indexOf('/* ---------- state'));
const ctx = {};
vm.createContext(ctx);
vm.runInContext(math + `
  var state = { targets: DEFAULT_TARGETS.map(t => ({ ...t })) };
  var __build = (base, keep) => { const c = computeTargets(); const r = buildScale(base, c.ys, 1, keep !== false); return { flag: r.baseFlag, steps: r.scale.map(s => ({ step: s.step, hex: s.hex, isBase: s.isBase })) }; };
`, ctx);

const data = JSON.parse(fs.readFileSync(themesPath, 'utf8'));
const blocks = [];
const notes = [];
for (const t of data.themes) {
  // keepBase: false (per theme) computes every step — for a base that would otherwise land on a step it
  // is too strong for (e.g. a vivid yellow on the pale 300 tint) and break that step's contrast role
  const primary = ctx.__build(t.primary, t.keepBase);
  const supplementary = ctx.__build(t.supplementary, t.keepBase);
  t.computed = {
    primary: Object.fromEntries(primary.steps.map((s) => [s.step, s.hex])),
    supplementary: Object.fromEntries(supplementary.steps.map((s) => [s.step, s.hex])),
  };
  for (const [name, r] of [['primary', primary], ['supplementary', supplementary]]) {
    if (r.flag) notes.push(`${t.key} ${name}: base ${t[name]} fits no step's role exactly — every step is computed, the base is approximated`);
  }
  if (t.key === 'default') continue;
  const g = t.graphicStep ?? 600;
  if (![600, 700, 800].includes(g)) throw new Error(`${t.key}: graphicStep must be 600, 700 or 800`);
  const step = (n) => `var(--pos-primitive-color-brand-primary-${n})`;
  const roles = [];
  if (g >= 700) roles.push(
    `    --pos-color-light-icon-interactive: ${step(g)};`,
    `    --pos-color-light-icon-interactive-hover: ${step(g + 200)};`,
    `    --pos-color-light-icon-interactive-active: ${step(g + 200)};`);
  if (g === 800) roles.push(
    `    --pos-color-light-interactive: ${step(800)};`,
    `    --pos-color-light-interactive-hover: ${step(1000)};`,
    `    --pos-color-light-interactive-active: ${step(1000)};`,
    `    --pos-color-dark-icon-interactive: ${step(300)};`,
    `    --pos-color-dark-icon-interactive-hover: ${step(100)};`,
    `    --pos-color-dark-icon-interactive-active: ${step(100)};`,
    `    --pos-color-dark-interactive: ${step(300)};`,
    `    --pos-color-dark-interactive-hover: ${step(100)};`,
    `    --pos-color-dark-interactive-active: ${step(100)};`);
  if (roles.length) roles.unshift(`    /* graphicStep ${g}: buttons, icons and other interactive graphics on step ${g} (dark mode: its mirror) */`);
  const lines = [
    ...primary.steps.map((s) => `    --pos-primitive-color-brand-primary-${s.step}: ${s.hex};${s.isBase ? ' /* base */' : ''}`),
    ...supplementary.steps.map((s) => `    --pos-primitive-color-brand-supplementary-${s.step}: ${s.hex};${s.isBase ? ' /* base */' : ''}`),
    ...roles,
  ];
  blocks.push(`  /* ${t.name} — ${t.description} primary ${t.primary}, supplementary ${t.supplementary} */\n  :root.pos-brand-${t.key} {\n${lines.join('\n')}\n  }`);
}

const css = `/*
  brand themes — GENERATED by npm run build:themes from tokens/themes.json; don't edit by hand.

  A theme overrides the brand-primary / brand-supplementary scale primitives. Every semantic and
  component token already points at those steps, so light, dark and high contrast follow on their own
  (HC keeps its own colors). A theme with graphicStep 700 / 800 also re-points the interactive
  graphic role tokens (buttons, icons) to that deeper step. Apply with a class on <html>: <html class="pos-brand-ocean">. No class =
  the Default theme (pos-primitives.css). Not in @layer, like the other token files: these values must
  override pos-primitives.css, which is unlayered too.
*/

${blocks.join('\n\n')}
`;
fs.writeFileSync(cssPath, css);
fs.writeFileSync(themesPath, JSON.stringify(data, null, 2) + '\n');
console.log(`build:themes — ${data.themes.length} themes (${blocks.length} CSS blocks) -> style/pos-themes.css`);
for (const n of notes) console.log('  note: ' + n);
